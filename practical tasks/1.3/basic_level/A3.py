pred = int(input("Предыдущее показание: "))
tek = int(input("Текущее показание: "))

# 1. Считаем объем израсходованного газа
if tek >= pred:
    gaz = tek - pred
else:
    # Если стрелка перешла через 9999 и пошла на новый круг
    gaz = 10000 - pred + tek

# 2. Считаем сумму к оплате по тарифам
if gaz <= 300:
    oplata = 21.0
elif gaz <= 600:
    oplata = 21.0 + (gaz - 300) * 0.06
elif gaz <= 800:
    oplata = 21.0 + 300 * 0.06 + (gaz - 600) * 0.04
else:
    oplata = 21.0 + 300 * 0.06 + 200 * 0.04 + (gaz - 800) * 0.025

# 3. Средняя цена за один кубометр
cena = oplata / gaz

# 4. Округляем до двух знаков (+ 0.0001 нужен для стандартного школьного округления вверх)
oplata = round(oplata + 0.0001, 2)
cena = round(cena + 0.0001, 2)

# Вывод результатов красивой табличкой
print("\nВывод:")
print(f"{'Предыдущее':<14} {'Текущее':<11} {'Использовано':<15} {'К оплате':<12} {'Ср. цена m^3':<12}")
print(f"{pred:<14} {tek:<11} {gaz:<15} {oplata:<12.2f} {cena:<12.2f}")